package ru.ashemchuk.model;

/**
 * Represents the four possible movement directions for a snake.
 */
public enum Direction {
    /**
     * Upwards direction (negative Y).
     */
    UP,
    /**
     * Downwards direction (positive Y).
     */
    DOWN,
    /**
     * Left direction (negative X).
     */
    LEFT,
    /**
     * Right direction (positive X).
     */
    RIGHT
}
